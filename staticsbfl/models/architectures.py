"""Two fixed dense reference models, and parameter accounting.

The populations of the study are generated by :mod:`staticsbfl.variation`;
:class:`SmallMLP` and :class:`WideMLP` are fixed dense classifiers kept as
small, well-understood fixtures for the spectrum, persistence and training
tests. :func:`count_parameters` and :func:`parameter_bytes` are what the
training step records for every generated model.

Every model exposes three attributes the rest of the package relies on:

    ``input_shape``        shape of a single un-batched input
    ``output_dim``         number of output logits
    ``hidden_layer_names`` the modules the hit spectrum counts, in forward
                           order, output layer deliberately excluded
"""

import math
from typing import Sequence, Tuple

import torch
import torch.nn as nn


class SmallMLP(nn.Module):
    """A compact dense classifier for CIFAR-10.

    ``3072 -> 256 -> 128 -> 10``, ReLU between. Layers are named individually
    rather than wrapped in a ``Sequential`` so that hook names stay readable in
    the suspiciousness output.
    """

    def __init__(
        self,
        num_classes: int = 10,
        input_shape: Sequence[int] = (3, 32, 32),
        hidden_dims: Sequence[int] = (256, 128),
    ) -> None:
        super().__init__()
        self.input_shape: Tuple[int, ...] = tuple(int(d) for d in input_shape)
        self.output_dim = int(num_classes)
        in_features = int(math.prod(self.input_shape))

        self.flatten = nn.Flatten()
        self.fc1 = nn.Linear(in_features, hidden_dims[0])
        self.fc2 = nn.Linear(hidden_dims[0], hidden_dims[1])
        self.head = nn.Linear(hidden_dims[1], num_classes)
        self.relu = nn.ReLU()

        self.hidden_layer_names: Tuple[str, ...] = ("fc1", "fc2")

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.flatten(x)
        x = self.relu(self.fc1(x))
        x = self.relu(self.fc2(x))
        return self.head(x)


class WideMLP(nn.Module):
    """The standard-sized dense counterpart of :class:`SmallMLP`.

    ``3072 -> 2048 -> 1024 -> 512 -> 10``. Same family, an order of magnitude
    more parameters, so capacity is the only thing that changed.
    """

    def __init__(
        self,
        num_classes: int = 10,
        input_shape: Sequence[int] = (3, 32, 32),
        hidden_dims: Sequence[int] = (2048, 1024, 512),
    ) -> None:
        super().__init__()
        self.input_shape: Tuple[int, ...] = tuple(int(d) for d in input_shape)
        self.output_dim = int(num_classes)
        in_features = int(math.prod(self.input_shape))

        self.flatten = nn.Flatten()
        self.fc1 = nn.Linear(in_features, hidden_dims[0])
        self.fc2 = nn.Linear(hidden_dims[0], hidden_dims[1])
        self.fc3 = nn.Linear(hidden_dims[1], hidden_dims[2])
        self.head = nn.Linear(hidden_dims[2], num_classes)
        self.relu = nn.ReLU()
        self.dropout = nn.Dropout(0.2)

        self.hidden_layer_names: Tuple[str, ...] = ("fc1", "fc2", "fc3")

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.flatten(x)
        x = self.dropout(self.relu(self.fc1(x)))
        x = self.dropout(self.relu(self.fc2(x)))
        x = self.relu(self.fc3(x))
        return self.head(x)


def count_parameters(model: nn.Module, trainable_only: bool = True) -> int:
    """Number of (trainable) parameters, for the training log."""
    params = model.parameters()
    if trainable_only:
        params = (p for p in model.parameters() if p.requires_grad)
    return sum(p.numel() for p in params)


def parameter_bytes(model: nn.Module) -> int:
    """Size of the model's parameters and buffers in bytes."""
    return sum(p.numel() * p.element_size() for p in model.parameters()) + sum(
        b.numel() * b.element_size() for b in model.buffers()
    )
