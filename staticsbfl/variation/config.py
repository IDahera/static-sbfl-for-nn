"""Architecture configurations and the samplers that generate them.

The point of this module is separation of concerns: **nothing here builds or
trains a model.** A configuration is a plain, frozen, hashable description of an
architecture, and every function that produces one is a pure function of its
arguments and a seeded generator. That makes the interesting property -- "does
every generated configuration stay inside the bounds it was drawn from?" --
checkable by a unit test that never touches torch, and it makes a whole
experiment reproducible from its seed alone.

Model construction lives in :mod:`staticsbfl.variation.builder`, which reads a config
and is not allowed to invent a dimension of its own.

Representing depth and width
----------------------------
A dense configuration is exactly one thing: ``hidden_widths``, a tuple of layer
widths. Depth is its length and width is its elements, so "add a layer" and
"change a layer's width" are the same operation on the same object. There is no
separate notion of adding a layer of initially unknown width -- a sampled
architecture is drawn whole, never patched.

Why not enumerate a pool of every combination
---------------------------------------------
Full enumeration is not available: with depth 1-10 and 151 admissible widths
there are :math:`\\sum_{d=1}^{10} 151^d \\approx 10^{21}` distinct width tuples.
:func:`sample_config_pool` therefore draws a pool of the requested size, dedupes
it and returns it as an ordered, inspectable list -- reproducible and
enumerable after the fact, which is what a pool is actually wanted for.
"""

from dataclasses import dataclass, replace
from typing import Dict, List, Optional, Tuple

import random

#: Activation functions a sampled architecture may use. Kept small and given
#: stable integer ids, because these become a categorical feature downstream.
ACTIVATIONS: Tuple[str, ...] = ("relu", "leaky_relu", "elu", "tanh", "sigmoid")

#: Stable id per activation. Append only -- never renumber, or cached datasets
#: generated by an earlier run stop meaning the same thing.
ACTIVATION_IDS: Dict[str, int] = {name: index for index, name in enumerate(ACTIVATIONS)}

#: Model families the variation machinery can describe. Only "mlp" is
#: implemented; the others are declared so the config type does not have to
#: change when they are added.
FAMILIES: Tuple[str, ...] = ("mlp", "cnn", "lstm")


class BoundsError(ValueError):
    """Raised when bounds are self-contradictory or a config violates them."""


@dataclass(frozen=True)
class VariationBounds:
    """The admissible region a configuration may be sampled from.

    Every bound is inclusive on both ends. Kept as its own object rather than as
    loose sampler arguments so that a phase can *state* its region, two regions
    can be checked for overlap (:meth:`overlaps`), and a generated config can be
    tested for membership (:meth:`contains`) without re-deriving the rule.
    """

    min_depth: int = 1
    max_depth: int = 10
    min_width: int = 32
    max_width: int = 512
    activations: Tuple[str, ...] = ACTIVATIONS
    family: str = "mlp"

    def __post_init__(self) -> None:
        if self.min_depth < 1:
            raise BoundsError(f"min_depth must be >= 1, got {self.min_depth}.")
        if self.max_depth < self.min_depth:
            raise BoundsError(
                f"max_depth ({self.max_depth}) is below min_depth ({self.min_depth})."
            )
        if self.min_width < 1:
            raise BoundsError(f"min_width must be >= 1, got {self.min_width}.")
        if self.max_width < self.min_width:
            raise BoundsError(
                f"max_width ({self.max_width}) is below min_width ({self.min_width})."
            )
        if not self.activations:
            raise BoundsError("At least one activation must be admissible.")
        unknown = sorted(set(self.activations) - set(ACTIVATIONS))
        if unknown:
            raise BoundsError(f"Unknown activation(s) {unknown}. Known: {list(ACTIVATIONS)}.")
        if self.family not in FAMILIES:
            raise BoundsError(f"Unknown family {self.family!r}. Known: {list(FAMILIES)}.")

    def contains(self, config: "ArchitectureConfig") -> bool:
        """Whether *config* lies inside this region, on every axis."""
        return (
            config.family == self.family
            and self.min_depth <= config.depth <= self.max_depth
            and all(self.min_width <= w <= self.max_width for w in config.hidden_widths)
            and config.activation in self.activations
        )

    def violations(self, config: "ArchitectureConfig") -> List[str]:
        """Human-readable reasons *config* is outside this region; empty if inside.

        Used by the tests and by the generation script's self-check, so a
        failure says which axis went out of range rather than just 'False'.
        """
        problems: List[str] = []
        if config.family != self.family:
            problems.append(f"family {config.family!r} != {self.family!r}")
        if not self.min_depth <= config.depth <= self.max_depth:
            problems.append(
                f"depth {config.depth} outside [{self.min_depth}, {self.max_depth}]"
            )
        offending = [w for w in config.hidden_widths if not self.min_width <= w <= self.max_width]
        if offending:
            problems.append(
                f"width(s) {offending} outside [{self.min_width}, {self.max_width}]"
            )
        if config.activation not in self.activations:
            problems.append(
                f"activation {config.activation!r} not in {list(self.activations)}"
            )
        return problems

    def overlaps(self, other: "VariationBounds") -> bool:
        """Whether two regions intersect on *every* axis at once.

        Phase 3 needs regions that do not overlap. Note the quantifier: two
        regions are disjoint as soon as **one** axis is disjoint, so this returns
        True only when depth, width and activations all intersect.
        """
        depth_overlap = not (
            self.max_depth < other.min_depth or other.max_depth < self.min_depth
        )
        width_overlap = not (
            self.max_width < other.min_width or other.max_width < self.min_width
        )
        activation_overlap = bool(set(self.activations) & set(other.activations))
        return depth_overlap and width_overlap and activation_overlap

    def describe(self) -> str:
        """One line for logs and folder manifests."""
        return (
            f"depth {self.min_depth}-{self.max_depth}, "
            f"width {self.min_width}-{self.max_width}, "
            f"activations {'/'.join(self.activations)}"
        )


@dataclass(frozen=True)
class ArchitectureConfig:
    """A complete, buildable description of one architecture.

    Frozen and hashable, so a pool can be deduplicated with a set and a config
    can be used as a dictionary key. It carries no torch objects and no file
    paths: it says *what* to build, and nothing about where the result goes.
    """

    key: str
    family: str
    hidden_widths: Tuple[int, ...]
    activation: str
    seed: int
    phase: str = ""
    split: str = ""

    @property
    def depth(self) -> int:
        """Number of hidden layers. The output layer is not one of them."""
        return len(self.hidden_widths)

    @property
    def total_hidden_units(self) -> int:
        """Neurons the spectrum will count, before the input shape is known."""
        return sum(self.hidden_widths)

    @property
    def activation_id(self) -> int:
        """Stable integer id, for use as a categorical feature."""
        return ACTIVATION_IDS[self.activation]

    @property
    def width_profile(self) -> str:
        """Coarse shape of the width sequence: narrowing, widening or mixed.

        Recorded because it is a property of the *architecture* that neither
        depth nor mean width captures, and a plausible predictor of where
        suspicious neurons concentrate.
        """
        if self.depth < 2:
            return "flat"
        diffs = [b - a for a, b in zip(self.hidden_widths, self.hidden_widths[1:])]
        if all(d <= 0 for d in diffs):
            return "narrowing"
        if all(d >= 0 for d in diffs):
            return "widening"
        return "mixed"

    def as_row(self) -> Dict[str, object]:
        """Flat dictionary for a manifest CSV or a feature table."""
        return {
            "key": self.key,
            "family": self.family,
            "phase": self.phase,
            "split": self.split,
            "seed": self.seed,
            "depth": self.depth,
            "activation": self.activation,
            "activation_id": self.activation_id,
            "min_width": min(self.hidden_widths),
            "max_width": max(self.hidden_widths),
            "mean_width": sum(self.hidden_widths) / self.depth,
            "total_hidden_units": self.total_hidden_units,
            "width_profile": self.width_profile,
            "hidden_widths": "-".join(str(w) for w in self.hidden_widths),
        }


# --------------------------------------------------------------------------
# Samplers -- pure functions of (bounds, generator)
# --------------------------------------------------------------------------


def sample_widths(
    rng: random.Random, bounds: VariationBounds, depth: Optional[int] = None
) -> Tuple[int, ...]:
    """Draw one width per hidden layer, each independently from the bounds.

    Widths are drawn **independently** rather than held constant across the
    model or forced to narrow monotonically. Two reasons:

    * a constant width makes width, depth and parameter count collinear, so
      their effects cannot be separated afterwards;
    * a per-neuron predictor needs its layer-width feature to vary *within* a
      model, otherwise every neuron of a model shares one value and the feature
      can only ever explain between-model variance.

    The resulting shape (narrowing / widening / mixed) is recorded on the config
    rather than imposed, so it stays available as an analysis variable.
    """
    if depth is None:
        depth = rng.randint(bounds.min_depth, bounds.max_depth)
    return tuple(rng.randint(bounds.min_width, bounds.max_width) for _ in range(depth))


def sample_config(
    rng: random.Random,
    bounds: VariationBounds,
    *,
    key: str,
    seed: int,
    phase: str = "",
    split: str = "",
) -> ArchitectureConfig:
    """Draw a single configuration from *bounds*.

    ``seed`` is the seed the *model* will later be initialised with; it is
    independent of the ``rng`` that draws the architecture, so the same
    architecture can be trained under several initialisations.
    """
    return ArchitectureConfig(
        key=key,
        family=bounds.family,
        hidden_widths=sample_widths(rng, bounds),
        activation=rng.choice(list(bounds.activations)),
        seed=seed,
        phase=phase,
        split=split,
    )


def sample_config_pool(
    bounds: VariationBounds,
    count: int,
    *,
    rng_seed: int,
    prefix: str = "cfg",
    phase: str = "",
    split: str = "",
    seed_start: int = 42,
    unique: bool = True,
    max_attempts_factor: int = 50,
) -> List[ArchitectureConfig]:
    """Draw *count* configurations from *bounds* as an ordered, inspectable pool.

    Args:
        bounds: the region to draw from.
        count: how many configurations to return.
        rng_seed: seeds the architecture sampler, so the pool is reproducible.
        prefix: key prefix; keys are ``<prefix>_000``, ``<prefix>_001``, ...
        seed_start: model-initialisation seed of the first config; subsequent
            configs get consecutive seeds.
        unique: drop duplicate architectures (same widths and activation).
            Turn this off for a bounds region too small to yield *count*
            distinct architectures.

    Raises:
        BoundsError: if *count* distinct configurations cannot be drawn.
    """
    if count < 1:
        raise BoundsError(f"count must be >= 1, got {count}.")

    rng = random.Random(rng_seed)
    pool: List[ArchitectureConfig] = []
    seen = set()
    attempts = 0
    limit = count * max_attempts_factor

    while len(pool) < count:
        attempts += 1
        if attempts > limit:
            raise BoundsError(
                f"Could not draw {count} distinct configurations from "
                f"{bounds.describe()} within {limit} attempts; the region is too "
                "small. Widen the bounds or pass unique=False."
            )
        candidate = sample_config(
            rng,
            bounds,
            key=f"{prefix}_{len(pool):03d}",
            seed=seed_start + len(pool),
            phase=phase,
            split=split,
        )
        signature = (candidate.hidden_widths, candidate.activation)
        if unique and signature in seen:
            continue
        seen.add(signature)
        pool.append(candidate)

    return pool


def with_seed(config: ArchitectureConfig, seed: int, *, key: str) -> ArchitectureConfig:
    """The same architecture under a different initialisation seed."""
    return replace(config, seed=seed, key=key)
